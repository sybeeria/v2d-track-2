#!/usr/bin/env bash
# Source after selecting NATIVE_ROOT, NATIVE_PROJECT and optionally NATIVE_WEIGHTS.
NATIVE_PROJECT=${NATIVE_PROJECT:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}
: "${NATIVE_ROOT:?set NATIVE_ROOT to a dedicated run/build directory}"
NATIVE_WEIGHTS=${NATIVE_WEIGHTS:-$NATIVE_ROOT/weights}
NATIVE_PYTHON=${NATIVE_PYTHON:-python}
NATIVE_MODULES=$NATIVE_PROJECT/external/video_to_data/reconstruction/modules
export NATIVE_ROOT NATIVE_PROJECT NATIVE_WEIGHTS NATIVE_PYTHON NATIVE_MODULES
export PYTHONPATH=$NATIVE_MODULES/v2d_cari4d/lib/cari4d:$NATIVE_MODULES/v2d_sam3d_body/lib:$NATIVE_MODULES/v2d_foundation_pose/lib/FoundationPose
export HF_HOME=$NATIVE_WEIGHTS/hf_home HF_HUB_DISABLE_IMPLICIT_TOKEN=1
export TORCH_HOME=$NATIVE_WEIGHTS/sam3d_body/torch_home
export SAM3D_BODY_ROOT=$NATIVE_MODULES/v2d_sam3d_body/lib MHR_ASSETS_ROOT=$NATIVE_WEIGHTS/sam3d_body
export FOUNDATIONPOSE_WEIGHTS_DIR=$NATIVE_WEIGHTS/foundationpose/nvlabs_pytorch
export PYOPENGL_PLATFORM=egl OPENCV_IO_ENABLE_OPENEXR=1 HDF5_USE_FILE_LOCKING=FALSE PYTHONUNBUFFERED=1
export MAX_JOBS=2 CMAKE_BUILD_PARALLEL_LEVEL=2 OMP_NUM_THREADS=2 MKL_NUM_THREADS=2 OPENBLAS_NUM_THREADS=2
export TORCH_CUDA_ARCH_LIST='8.0 8.6 8.9 9.0'
